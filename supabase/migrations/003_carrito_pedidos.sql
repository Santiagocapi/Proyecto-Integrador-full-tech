
-- 1. Productos guardados en el carrito de cada usuario
CREATE TABLE public.cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    variant_id BIGINT NOT NULL REFERENCES public.product_variants(id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    UNIQUE (user_id, variant_id)
);

-- 2. Pedidos realizados por los usuarios
CREATE TABLE public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES public.profiles(id),
    tracking_code TEXT NOT NULL UNIQUE,
    status TEXT NOT NULL DEFAULT 'pendiente'
        CHECK (status IN ('pendiente', 'pagado', 'enviado', 'entregado', 'cancelado')),
    total NUMERIC(10, 2) NOT NULL CHECK (total >= 0),
    shipping_name TEXT NOT NULL,
    shipping_address TEXT NOT NULL,
    shipping_city TEXT NOT NULL,
    shipping_zip TEXT NOT NULL,
    shipping_phone TEXT NOT NULL,
    payment_method TEXT NOT NULL
        CHECK (payment_method IN ('tarjeta', 'transferencia', 'efectivo')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Detalle de los productos de cada pedido
CREATE TABLE public.order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES public.orders(id) ON DELETE CASCADE,
    variant_id BIGINT NOT NULL REFERENCES public.product_variants(id),
    product_name TEXT NOT NULL,
    variant_name TEXT NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL CHECK (unit_price >= 0),
    quantity INTEGER NOT NULL CHECK (quantity > 0)
);
